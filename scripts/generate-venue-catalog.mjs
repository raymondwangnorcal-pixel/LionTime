#!/usr/bin/env node
/**
 * generate-venue-catalog.mjs — writes lib/venue-catalog.generated.mjs from the
 * VENUES array in index.html (DEC-0069).
 *
 * The generated module is what everything outside the page imports when it
 * needs to know which venues exist: the seed-vote bot, the (planned) Telegram
 * bot's alias table, and the (planned) override target registry. It is
 * committed, because GitHub Actions jobs read it without running a build;
 * `npm run build --check` and the test suite fail if it is out of date.
 */
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadVenues, hasWeeklyHours } from './lib/venues.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Short names people actually type. Derived, not hand-maintained. */
function aliasesFor(venue) {
  const out = new Set();
  const name = venue.name;
  out.add(name);
  const stripped = name
    .replace(/\s*\((.+)\)\s*$/, ' $1')          // "Joe's Coffee (NoCo)" → "Joe's Coffee NoCo"
    .replace(/\b(Library|Dining Hall|Dining|Cafe|Gym|Hall)\b/g, '')
    .replace(/\s{2,}/g, ' ').trim();
  if (stripped && stripped !== name) out.add(stripped);
  const paren = name.match(/\(([^)]+)\)/)?.[1];
  if (paren) out.add(paren);                      // "NoCo", "2nd Floor"
  out.add(venue.id);
  return [...out].map(a => a.toLowerCase());
}

export function buildCatalog(venues = loadVenues(ROOT)) {
  return venues.map(v => ({
    id: v.id,
    name: v.name,
    cat: v.cat,
    loc: v.loc ?? null,
    parentId: v.parentId ?? null,
    weeklyHours: hasWeeklyHours(v) ? v.hours : null,
    aliases: aliasesFor(v),
  }));
}

export function renderCatalogModule(catalog) {
  const body = JSON.stringify(catalog, null, 2);
  return `/* GENERATED by scripts/generate-venue-catalog.mjs from the VENUES array in
   index.html — do not edit. Run \`npm run build\` after changing VENUES. */

export const VENUE_CATALOG = Object.freeze(${body});

export const VENUE_BY_ID = Object.freeze(Object.fromEntries(VENUE_CATALOG.map(v => [v.id, v])));

/** Venues in a category that have a fixed weekly schedule (live-only ones are excluded). */
export function venuesWithHours(cat) {
  return VENUE_CATALOG.filter(v => v.cat === cat && v.weeklyHours);
}

/** Case-insensitive lookup by name, alias, or id. Returns every match. */
export function findVenues(text) {
  const needle = String(text || '').trim().toLowerCase();
  if (!needle) return [];
  return VENUE_CATALOG.filter(v => v.aliases.includes(needle));
}
`;
}

export const OUTPUT_PATH = join(ROOT, 'lib', 'venue-catalog.generated.mjs');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const catalog = buildCatalog();
  writeFileSync(OUTPUT_PATH, renderCatalogModule(catalog));
  console.log(`✓ lib/venue-catalog.generated.mjs (${catalog.length} venues)`);
}
