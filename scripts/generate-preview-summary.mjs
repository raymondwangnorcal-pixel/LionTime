#!/usr/bin/env node
/**
 * generate-preview-summary.mjs — builds the compact payload behind
 * /api/preview: the category list, the venues in each, and each venue's
 * baseline weekly hours.
 *
 * This is what external surfaces (the Gapless Labs studio site) embed as a
 * live LionHour preview. It is deliberately small and boring: no status is
 * computed here, only schedules. The consumer compares them against its own
 * clock, so a cached response still ticks and still flips open/closed at the
 * right minute.
 *
 * Generated from VENUE_CATALOG, which is itself generated from the VENUES
 * array in index.html — so index.html stays the single source of truth
 * (DEC-0069). Run `npm run build` after changing VENUES.
 *
 * Output: lib/preview-summary.generated.mjs (imported by api/preview.js, so
 * Vercel always bundles it with the function).
 */
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { VENUE_CATALOG } from '../lib/venue-catalog.generated.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/* Mirrors CATEGORIES in index.html, minus the "All" tab. Order is the order
   the preview shows them in. */
const CATEGORIES = [
  { id: 'library', label: 'Libraries', icon: '📚' },
  { id: 'dining', label: 'Dining', icon: '🍜' },
  { id: 'cafe', label: 'Cafes', icon: '☕' },
  { id: 'fitness', label: 'Fitness', icon: '💪' },
  { id: 'student', label: 'Student Life & Services', icon: '🎓' },
];

/** Venue ids whose hours are refreshed live by a scraper, per category. */
const LIVE_CATEGORIES = ['library', 'dining', 'cafe', 'fitness', 'student'];

const EMPTY_WEEK = { 0: [], 1: [], 2: [], 3: [], 4: [], 5: [], 6: [] };

function venuesFor(catId) {
  return VENUE_CATALOG
    // Sub-venues (Uris Pool inside Dodge) are detail the preview does not need.
    .filter((venue) => venue.cat === catId && !venue.parentId)
    .map((venue) => {
      /* A few venues publish no baseline at all — their hours exist only in
         the live feed. Emit an empty week so every venue has the same shape,
         and flag it, so a consumer without live data can say "hours not
         published" instead of the flatly wrong "closed". */
      const published = Boolean(venue.weeklyHours && Object.keys(venue.weeklyHours).length === 7);
      return {
        id: venue.id,
        name: venue.name,
        loc: venue.loc || '',
        published,
        hours: published ? venue.weeklyHours : { ...EMPTY_WEEK },
      };
    });
}

const summary = {
  schemaVersion: 1,
  timezone: 'America/New_York',
  source: 'https://lionhour.com',
  categories: CATEGORIES.map((category) => ({
    ...category,
    live: LIVE_CATEGORIES.includes(category.id),
    venues: venuesFor(category.id),
  })),
};

const total = summary.categories.reduce((sum, c) => sum + c.venues.length, 0);
if (!total) {
  console.error('✗ preview summary is empty — VENUE_CATALOG did not load');
  process.exit(1);
}

const body = `/* GENERATED by scripts/generate-preview-summary.mjs from
   lib/venue-catalog.generated.mjs — do not edit. Run \`npm run build\`.

   Baseline schedules behind /api/preview. No status is computed here; the
   consumer applies its own clock so a cached response still ticks. */

export const PREVIEW_SUMMARY = Object.freeze(${JSON.stringify(summary, null, 2)});
`;

writeFileSync(join(ROOT, 'lib/preview-summary.generated.mjs'), body);
console.log(`✓ lib/preview-summary.generated.mjs — ${summary.categories.length} categories, ${total} venues`);
